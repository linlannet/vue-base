export function createI18n(locale: 'zh-CN' | 'en' = 'zh-CN') {
  return {
    locale,
    t(key: string): string {
      return DICT[locale]?.[key] ?? DICT['zh-CN'][key] ?? key
    }
  }
}

export type I18n = ReturnType<typeof createI18n>
